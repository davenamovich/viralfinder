"use client";

import { useEffect, useState } from "react";
import type { InternationalAdaptation, TrendOpportunity } from "@/lib/trend-scout/types";
import { languageLabel } from "@/lib/trend-scout/types";
import { Globe, Loader2, Sparkles } from "lucide-react";

interface Props {
  trend: TrendOpportunity;
  onSelectForRebuild?: (lang: string) => void;
  selectedLanguages?: string[];
}

interface State {
  loading: boolean;
  adaptations: InternationalAdaptation[];
  source: "llm" | "fallback" | "loading";
  raw?: string;
  error?: string;
}

export function InternationalPanel({ trend, onSelectForRebuild, selectedLanguages = [] }: Props) {
  const [state, setState] = useState<State>({
    loading: true,
    adaptations: [],
    source: "loading",
  });

  useEffect(() => {
    let cancelled = false;
    (async () => {
      setState((s) => ({ ...s, loading: true, error: undefined }));
      try {
        const res = await fetch("/api/trend-scout/international", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ trend }),
        });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const data = (await res.json()) as Omit<State, "loading">;
        if (!cancelled) setState({ ...data, loading: false });
      } catch (e) {
        if (!cancelled) {
          setState({
            loading: false,
            adaptations: [],
            source: "fallback",
            error: e instanceof Error ? e.message : "International recommendation failed",
          });
        }
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [trend.id, trend.title]);

  if (state.loading) {
    return (
      <div className="rounded-xl border border-white/[0.06] bg-white/[0.02] p-6 text-center">
        <Loader2 className="h-5 w-5 mx-auto mb-2 text-[var(--pr-electric)] animate-spin" />
        <p className="text-xs text-[var(--pr-text-dim)]">
          Rewriting angles for cultural fluency…
        </p>
      </div>
    );
  }

  return (
    <div className="space-y-3">
      <header className="flex items-start gap-3 pr-card-grad pr-border-grad rounded-xl p-4">
        <div className="h-9 w-9 rounded-lg bg-[var(--pr-gold)]/10 flex items-center justify-center shrink-0">
          <Globe className="h-4.5 w-4.5 text-[var(--pr-gold)]" />
        </div>
        <div className="min-w-0">
          <div className="text-[10px] uppercase tracking-[0.18em] text-[var(--pr-text-mute)] mb-0.5">
            International adaptation
          </div>
          <h2 className="text-base sm:text-lg font-semibold leading-tight">{trend.title}</h2>
          <div className="text-[11px] text-[var(--pr-text-mute)] mt-1">
            Primary market: <strong>{trend.countryLabel} / {trend.languageLabel}</strong>
            {" · "}
            Generated by: <strong className={state.source === "llm" ? "text-[var(--pr-electric)]" : "text-[var(--pr-gold)]"}>
              {state.source === "llm" ? "P&R Thought Engine (LLM)" : "Deterministic fallback"}
            </strong>
          </div>
        </div>
      </header>

      {state.error && (
        <div className="text-xs text-amber-300 bg-amber-500/10 border border-amber-500/20 rounded-lg p-2">
          {state.error} — showing fallback adaptations.
        </div>
      )}

      <ul className="space-y-3">
        {state.adaptations.map((a) => {
          const selected = selectedLanguages.includes(a.language);
          return (
            <li
              key={a.language}
              className={`rounded-xl border p-4 transition-all cursor-pointer ${
                selected
                  ? "border-[var(--pr-electric)]/40 bg-[var(--pr-electric)]/[0.06] pr-glow"
                  : "border-white/[0.06] bg-white/[0.02] hover:border-white/[0.12]"
              }`}
              onClick={() => onSelectForRebuild?.(a.language)}
            >
              <div className="flex items-center justify-between gap-2 mb-2">
                <div className="flex items-center gap-2">
                  <span className="text-xs font-bold uppercase tracking-wider text-[var(--pr-electric)]">
                    {a.language}
                  </span>
                  <span className="text-xs text-[var(--pr-text-dim)]">·</span>
                  <span className="text-sm font-medium">{a.languageLabel}</span>
                </div>
                {selected && (
                  <span className="text-[10px] px-2 py-0.5 rounded-full bg-[var(--pr-electric)]/15 text-[var(--pr-electric)] border border-[var(--pr-electric)]/30">
                    Selected for rebuild
                  </span>
                )}
              </div>
              <p className="text-sm text-foreground/90 leading-relaxed mb-2">{a.angle}</p>
              <div className="rounded-lg bg-black/30 border border-white/[0.04] p-2 mb-2">
                <div className="text-[10px] uppercase tracking-[0.18em] text-[var(--pr-text-mute)] mb-1 inline-flex items-center gap-1">
                  <Sparkles className="h-3 w-3 text-[var(--pr-gold)]" /> Hook
                </div>
                <p className="text-sm italic text-foreground/85">“{a.hook}”</p>
              </div>
              <div className="text-[11px] text-[var(--pr-text-mute)]">
                <strong className="text-[var(--pr-text-dim)]">Cultural note:</strong> {a.culturalNote}
              </div>
            </li>
          );
        })}
      </ul>

      <div className="text-[10px] text-[var(--pr-text-mute)] italic">
        Angles are rewritten for cultural fluency, never translated word-for-word. Tap a market to add
        it to the “Rebuild for the World” target languages list.
      </div>
    </div>
  );
}
