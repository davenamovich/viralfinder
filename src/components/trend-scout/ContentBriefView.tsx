"use client";

import type { ContentBrief, TrendOpportunity } from "@/lib/trend-scout/types";
import { Brain, FileText, Mic, Image as ImageIcon, Target, AlertTriangle, Globe, Sparkles } from "lucide-react";

interface Props {
  brief: ContentBrief;
  trend: TrendOpportunity;
  source: "llm" | "fallback" | "loading";
  raw?: string;
  /** Number of Exa web sources used to enrich this brief (0 = not enriched) */
  exaSources?: number;
}

export function ContentBriefView({ brief, trend, source, raw, exaSources = 0 }: Props) {
  return (
    <div className="space-y-4">
      <header className="flex items-start gap-3 pr-card-grad pr-border-grad rounded-xl p-4">
        <div className="h-10 w-10 rounded-lg bg-[var(--pr-electric)]/10 flex items-center justify-center shrink-0">
          <Brain className="h-5 w-5 text-[var(--pr-electric)]" />
        </div>
        <div className="min-w-0 flex-1">
          <div className="flex items-center gap-2 flex-wrap">
            <div className="text-[10px] uppercase tracking-[0.18em] text-[var(--pr-text-mute)]">
              Creative Intelligence brief
            </div>
            {exaSources > 0 && (
              <span
                title="Real-time web context from Exa (via Agent Reach) was injected into the LLM prompt"
                className="inline-flex items-center gap-1 text-[10px] px-2 py-0.5 rounded-full bg-[var(--pr-gold)]/10 text-[var(--pr-gold)] border border-[var(--pr-gold)]/25 font-semibold uppercase tracking-wider"
              >
                <Sparkles className="h-3 w-3" />
                Enriched ×{exaSources} Exa sources
              </span>
            )}
          </div>
          <h2 className="text-base sm:text-lg font-semibold leading-tight mt-0.5">{trend.title}</h2>
          <div className="text-[11px] text-[var(--pr-text-mute)] mt-1">
            Best format: <strong className="text-[var(--pr-gold)]">{brief.bestFormat}</strong>
            {" · "}
            Generated by: <strong className={source === "llm" ? "text-[var(--pr-electric)]" : "text-[var(--pr-gold)]"}>
              {source === "llm" ? "P&R Thought Engine (LLM)" : source === "loading" ? "Generating…" : "Deterministic fallback"}
            </strong>
            {exaSources > 0 && (
              <>
                {" · "}
                <span className="text-[var(--pr-text-dim)]">
                  + Exa real-time web context ({exaSources} source{exaSources === 1 ? "" : "s"})
                </span>
              </>
            )}
          </div>
        </div>
      </header>

      {source === "loading" ? (
        <div className="rounded-xl border border-white/[0.06] bg-white/[0.02] p-8 text-center">
          <div className="inline-flex items-center gap-2 text-sm text-[var(--pr-text-dim)]">
            <span className="h-3 w-3 rounded-full bg-[var(--pr-electric)] animate-pulse" />
            Generating brief from the Thought Engine…
          </div>
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
          <BriefBlock icon={<Mic className="h-4 w-4" />} label="The real conversation">
            {brief.realConversation}
          </BriefBlock>
          <BriefBlock icon={<Target className="h-4 w-4" />} label="Contrarian or useful angle">
            {brief.contrarianOrUsefulAngle}
          </BriefBlock>
          <BriefBlock icon={<Brain className="h-4 w-4" />} label="Who this is for">
            {brief.audience}
          </BriefBlock>
          <BriefBlock icon={<FileText className="h-4 w-4" />} label="Hook (first 3 seconds)">
            <em>“{brief.hook}”</em>
          </BriefBlock>
          <BriefBlock icon={<ImageIcon className="h-4 w-4" />} label="30-second script direction" full>
            {brief.scriptDirection}
          </BriefBlock>
          <BriefBlock icon={<ImageIcon className="h-4 w-4" />} label="Visual treatment" full>
            {brief.visualTreatment}
          </BriefBlock>
          <BriefBlock icon={<Target className="h-4 w-4" />} label="CTA" full>
            {brief.cta}
          </BriefBlock>
          <BriefBlock icon={<Globe className="h-4 w-4" />} label="Suggested target languages" full>
            <div className="flex flex-wrap gap-1.5">
              {brief.suggestedLanguages.map((l) => (
                <span
                  key={l}
                  className="text-xs px-2 py-0.5 rounded-full bg-[var(--pr-electric)]/10 text-[var(--pr-electric)] border border-[var(--pr-electric)]/20"
                >
                  {l.toUpperCase()}
                </span>
              ))}
            </div>
          </BriefBlock>
          <BriefBlock
            icon={<AlertTriangle className="h-4 w-4 text-[var(--pr-gold)]" />}
            label="Risk notes"
            full
            tone="warning"
          >
            {brief.riskNotes}
          </BriefBlock>

          {raw && (
            <details className="lg:col-span-2 group">
              <summary className="text-xs text-[var(--pr-text-mute)] cursor-pointer hover:text-foreground transition-colors select-none">
                Show raw LLM output (for audit)
              </summary>
              <pre className="mt-2 p-3 rounded-lg bg-black/40 border border-white/[0.04] text-[11px] text-[var(--pr-text-dim)] overflow-x-auto whitespace-pre-wrap font-mono max-h-72 pr-scrollbar">
                {raw}
              </pre>
            </details>
          )}
        </div>
      )}
    </div>
  );
}

function BriefBlock({
  icon,
  label,
  children,
  full,
  tone,
}: {
  icon: React.ReactNode;
  label: string;
  children: React.ReactNode;
  full?: boolean;
  tone?: "warning";
}) {
  return (
    <div
      className={`rounded-xl border bg-white/[0.02] p-4 pr-border-grad ${
        tone === "warning" ? "border-[var(--pr-gold)]/20" : "border-white/[0.06]"
      } ${full ? "lg:col-span-2" : ""}`}
    >
      <div className="flex items-center gap-2 text-[10px] uppercase tracking-[0.18em] text-[var(--pr-text-mute)] mb-2">
        <span className={tone === "warning" ? "text-[var(--pr-gold)]" : "text-[var(--pr-electric)]"}>
          {icon}
        </span>
        <span>{label}</span>
      </div>
      <div className="text-sm text-foreground/90 leading-relaxed">{children}</div>
    </div>
  );
}
